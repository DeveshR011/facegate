"""Regenerate engine/src/mask_bitmap.hpp from the mask polygon in facegate/core/occlusion.py.

The Python and C++ engines must paint out exactly the same pixels, or templates
enrolled by one would not match probes embedded by the other. The bitmap is
rasterised once here with OpenCV so the C++ side needs no polygon code.

    python tools/gen_mask_header.py          # rewrite the header
    python tools/gen_mask_header.py --check  # exit 1 if the header is stale (used by tests)
"""

from __future__ import annotations

import sys
from pathlib import Path

import cv2
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from facegate.core.occlusion import _MASK_POLY  # noqa: E402

HEADER = ROOT / "engine" / "src" / "mask_bitmap.hpp"


def render() -> str:
    canvas = np.zeros((112, 112), dtype=np.uint8)
    cv2.fillPoly(canvas, [_MASK_POLY], 1)
    rows = ",\n".join(f'    "{"".join("#" if v else "." for v in row)}"' for row in canvas)
    return (
        "// GENERATED by tools/gen_mask_header.py from facegate/core/occlusion.py - do not edit.\n"
        "// '#' marks pixels painted out (set to 127) in the \"mask\" view of the 112x112 crop.\n"
        "#pragma once\n\n"
        "namespace fg {\n"
        "static const char* const kMaskRows[112] = {\n"
        f"{rows}\n"
        "};\n"
        "}  // namespace fg\n"
    )


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        current = HEADER.read_text(encoding="utf-8").replace("\r\n", "\n") if HEADER.exists() else ""
        sys.exit(0 if current == text else 1)
    HEADER.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {HEADER}")
